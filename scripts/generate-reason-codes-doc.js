#!/usr/bin/env node
/**
 * generate-reason-codes-doc.js
 *
 * Regenerates the `reason_code` catalog table in docs/USAGE.md from the
 * canonical catalog at schemas/reason-codes.json (GitHub Issue #731).
 *
 * The catalog is the single source of truth: schemas/reason-codes.json is
 * validated by the CI lock tests in __tests__/reason-codes.test.ts, while the
 * Markdown table in docs/USAGE.md is what operators actually read. Before this
 * script the two could drift silently — a new code could ship in the JSON and
 * never reach the docs, or a hand-edited table could document a code the
 * action no longer emits.
 *
 * The generated region is delimited by sentinel comments so the script is
 * idempotent and safe to re-run:
 *
 *   <!-- BEGIN GENERATED: reason-codes (source: schemas/reason-codes.json) -->
 *   | `reason_code` | ... |
 *   <!-- END GENERATED: reason-codes -->
 *
 * Anything a human writes outside the sentinels is preserved untouched.
 *
 * Usage:
 *   node scripts/generate-reason-codes-doc.js           # write the table
 *   node scripts/generate-reason-codes-doc.js --check   # CI: fail on drift
 *
 * Exit codes:
 *   0 — table written, or already up to date (idempotent no-op)
 *   1 — drift detected in --check mode, sentinels missing, or bad input
 *
 * No dependencies beyond Node built-ins, so it runs on Node 20+ with no
 * install step.
 */

'use strict';

const { readFileSync, writeFileSync } = require('fs');
const { resolve, relative } = require('path');

const REPO_ROOT = resolve(__dirname, '..');
const CATALOG_PATH = resolve(REPO_ROOT, 'schemas', 'reason-codes.json');
const DOC_PATH = resolve(REPO_ROOT, 'docs', 'USAGE.md');

const REGION_ID = 'reason-codes';
const CATALOG_SOURCE = 'schemas/reason-codes.json';
const BEGIN_MARKER = `<!-- BEGIN GENERATED: ${REGION_ID} (source: ${CATALOG_SOURCE}) -->`;
const END_MARKER = `<!-- END GENERATED: ${REGION_ID} -->`;

/**
 * Column order is part of the contract: consumers (and the tests) rely on it
 * staying stable so a regenerated table produces a minimal diff.
 */
const COLUMNS = [
  { header: '`reason_code`', key: 'code', render: (c) => `\`${c.code}\`` },
  { header: '`valid`', key: 'valid', render: (c) => boolCell(c.valid) },
  { header: '`account_funded`', key: 'accountFunded', render: (c) => boolCell(c.accountFunded) },
  { header: '`trustline_exists`', key: 'trustlineExists', render: (c) => boolCell(c.trustlineExists) },
  { header: '`xlm_reserve_met`', key: 'xlmReserveMet', render: (c) => boolCell(c.xlmReserveMet) },
  { header: 'Description', key: 'description', render: (c) => renderDescription(c) },
];

function boolCell(value) {
  if (value === true) return '✅ `true`';
  if (value === false) return '❌ `false`';
  return '—';
}

/**
 * Render one description cell.
 *
 * A `|` inside a description would end the Markdown table cell, and a newline
 * would break the row, so both are escaped. Deprecated entries are rendered
 * with strikethrough so a removed-but-still-documented code is visibly
 * retired rather than silently deleted.
 */
function renderDescription(entry) {
  const raw = typeof entry.description === 'string' ? entry.description.trim() : '';
  const text = raw.replace(/\|/g, '\\|').replace(/\r?\n/g, ' ').trim();
  if (entry.deprecated) {
    return `~~${text}~~`;
  }
  return text;
}

function buildTable(catalog) {
  const header = `| ${COLUMNS.map((c) => c.header).join(' | ')} |`;
  const divider = `|${COLUMNS.map(() => ' --- ').join('|')}|`;

  const rows = catalog.codes.map((entry) => {
    const cells = COLUMNS.map((c) => c.render(entry));
    return `| ${cells.join(' | ')} |`;
  });

  return [header, divider, ...rows].join('\n');
}

function buildRegion(catalog) {
  const codes = catalog.codes.length;
  const version = catalog.version;
  return [
    BEGIN_MARKER,
    `<!-- AUTOGENERATED — do not edit by hand. Run \`npm run reason-codes:doc\`. -->`,
    `<!-- ${codes} codes from ${CATALOG_SOURCE} (catalog version ${version}). -->`,
    '',
    buildTable(catalog),
    '',
    END_MARKER,
  ].join('\n');
}

function findRegion(doc, markers) {
  const beginIndex = doc.indexOf(markers.begin);
  if (beginIndex === -1) {
    throw new Error(
      `Missing generated-region start marker in ${markers.docRelative}. Expected:\n  ${markers.begin}`,
    );
  }
  const endIndex = doc.indexOf(markers.end, beginIndex + markers.begin.length);
  if (endIndex === -1) {
    throw new Error(
      `Missing generated-region end marker in ${markers.docRelative}. Expected:\n  ${markers.end}`,
    );
  }
  return {
    start: beginIndex,
    end: endIndex + markers.end.length,
  };
}

function main(argv) {
  const checkOnly = argv.includes('--check');
  const catalog = JSON.parse(readFileSync(CATALOG_PATH, 'utf8'));

  if (!catalog || !Array.isArray(catalog.codes) || catalog.codes.length === 0) {
    console.error(
      `[generate-reason-codes-doc] FAIL  ${CATALOG_SOURCE} has no "codes" array — refusing to regenerate.`,
    );
    return 1;
  }

  const doc = readFileSync(DOC_PATH, 'utf8');
  const markers = {
    begin: BEGIN_MARKER,
    end: END_MARKER,
    docRelative: relative(REPO_ROOT, DOC_PATH).replace(/\\/g, '/'),
  };

  let region;
  try {
    region = findRegion(doc, markers);
  } catch (error) {
    console.error(`[generate-reason-codes-doc] FAIL  ${error.message}`);
    return 1;
  }

  const current = doc.slice(region.start, region.end);
  const next = buildRegion(catalog);

  if (current === next) {
    console.log(
      `[generate-reason-codes-doc] OK  ${markers.docRelative} is up to date (${catalog.codes.length} codes).`,
    );
    return 0;
  }

  if (checkOnly) {
    console.error(
      `[generate-reason-codes-doc] FAIL  ${markers.docRelative} is out of date with ${CATALOG_SOURCE}.\n` +
        `         Run \`npm run reason-codes:doc\` and commit the result.`,
    );
    return 1;
  }

  const updated = doc.slice(0, region.start) + next + doc.slice(region.end);
  writeFileSync(DOC_PATH, updated, 'utf8');
  console.log(
    `[generate-reason-codes-doc] Wrote ${markers.docRelative} (${catalog.codes.length} codes, catalog version ${catalog.version}).`,
  );
  return 0;
}

process.exit(main(process.argv.slice(2)));
